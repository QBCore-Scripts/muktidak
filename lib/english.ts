export function englishText(text: string) {
  return phrases[text] || text;
}

export function englishActivity(item: Activity): Activity {
  const next = activities[item.id];
  return next ? { ...item, ...next } : item;
}

export function englishNotice(item: Notice): Notice {
  const next = notices[item.id];
  return next ? { ...item, ...next } : item;
}

export function latinDigits(value: string) {
  return value.replace(/[০-৯]/g, (digit) => String("০১২৩৪৫৬৭৮৯".indexOf(digit)));
}

export function telHref(phone: string) {
  const dial = latinDigits(phone).replace(/[^\d+]/g, "");
  return dial ? `tel:${dial}` : "";
}
